let current = DEFAULT_LANGUAGE;

export function getLanguage() {
  return current;
}

export function setLanguage(language) {
  current = Object.hasOwn(messages, language) ? language : DEFAULT_LANGUAGE;
  return current;
}

export function locale(language = current) {
  return LOCALES[language] ?? LOCALES[DEFAULT_LANGUAGE];
}

// Picks a supported language from a list such as navigator.languages.
export function matchLanguage(candidates = []) {
  for (const candidate of candidates) {
    const base = String(candidate ?? '').toLowerCase().split('-')[0];
    if (Object.hasOwn(messages, base)) return base;
  }
  return null;
}

export function t(key, params = {}) {
  const template = messages[current]?.[key] ?? messages[DEFAULT_LANGUAGE][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

export function keys(language) {
  return Object.keys(messages[language] ?? {});
}
